"""walk.py (registered in 09): partial-product walk of ASS-words, injectivity, reachable indices, prefix tree.
   ValaQuenta/.venv/bin/python walk.py"""
import sys, os, csv, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import equation_space as Q
GEN = {"A": 1, "S": 2, "G": 4}
def walk(word):
    v = (1, 0); out = [v]
    for ch in word:
        if ch in GEN: v = Q.mul(v, (1, GEN[ch])); out.append(v)
    return tuple(out)
here = os.path.dirname(os.path.abspath(__file__)); rows = []
for fn, col in (("catalog/archimedes_ufm.csv", "loop_word"), ("catalog/archimedes_py.csv", "ass_word")):
    for r in csv.DictReader(open(os.path.join(here, fn))): rows.append(r[col])
words = sorted({"".join(c for c in w if c in GEN) for w in rows if any(c in GEN for c in w)})
words = [w for w in words if 1 <= len(w) <= 400]
print("distinct words: %d, total letters %d" % (len(words), sum(map(len, words))))
walks = {w: walk(w) for w in words}
print("W1 distinct walks %d of %d words; index-only walks distinct %d" % (len({walks[w] for w in words}), len(words), len({tuple(k for s, k in walks[w]) for w in words})))
reach = sorted({k for w in words for s, k in walks[w]}); print("W2 reachable indices:", reach, "(%d of 16)" % len(reach))
# prefix tree
nodes = {(): 0}; 
for w in words:
    for i in range(1, len(w) + 1): nodes.setdefault(w[:i], 0)
tot = sum(map(len, words)); print("W3 prefix tree nodes %d, letters %d, ratio %.3f" % (len(nodes), tot, len(nodes) / tot))
first = collections.Counter(w[0] for w in words); print("W4 first-letter split:", {k: "%.1f%%" % (100 * v / len(words)) for k, v in first.items()})
dep = collections.Counter(len(p) for p in nodes); print("nodes by depth (1..12):", [dep[i] for i in range(1, 13)])
# which prefixes are shared by many words: top 10 internal nodes by subtree word count
cnt = collections.Counter()
for w in words:
    for i in range(1, len(w) + 1): cnt[w[:i]] += 1
print("most shared prefixes (len>=3):", [(p, c) for p, c in cnt.most_common(400) if len(p) >= 3][:10])
# the group generated by the three letters acting on indices: orbit of the walk endpoint
ends = collections.Counter(walks[w][-1] for w in words); print("endpoints (sign,index) occupied: %d of 16" % len(ends))
